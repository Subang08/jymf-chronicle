  function plain(v) {
    if (v === null || v === undefined) return '';
    if (typeof v === 'string') return v;
    if (typeof v === 'number') return isFinite(v) ? String(v) : '';
    if (typeof v === 'boolean') return v ? '是' : '否';
    if (typeof v === 'object' && typeof v.name === 'string') return v.name;
    return '';
  }

  function firstOf() {
    for (var i = 0; i < arguments.length; i++) {
      var t = plain(arguments[i]);
      if (t !== '') return t;
    }
    return '';
  }

  function numOr(v, d) {
    var n = Number(v);
    return isFinite(n) ? Math.floor(n) : d;
  }

  // 把任意 ctx 归一成一张可安全取值的词表：缺项走兜底，不留空洞。
  function bag(ctx) {
    ctx = ctx || {};
    var b = {};
    var i, k;
    for (i = 0; i < PLAIN_KEYS.length; i++) {
      k = PLAIN_KEYS[i];
      b[k] = firstOf(ctx[k], FALLBACK[k]);
    }

    var m = ctx.month;
    if (typeof m === 'string' && m !== '') b.month = m;
    else if (MONTH_NAMES[numOr(m, 0)]) b.month = MONTH_NAMES[numOr(m, 0)];
    else b.month = FALLBACK.month;

    var pc = ctx.pc;
    var pco = (pc && typeof pc === 'object') ? pc : null;
    if (typeof pc === 'string' && pc !== '') b.pc = pc;
    else b.pc = firstOf(pco && pco.name, ctx.pcName, FALLBACK.pc);
    b.race = firstOf(pco && pco.raceName, pco && pco.race, ctx.race, FALLBACK.race);
    b.cls = firstOf(pco && pco.clsName, pco && pco.cls, pco && pco.job, ctx.cls, FALLBACK.cls);
    b.level = numOr(ctx.level, numOr(pco && pco.level, FALLBACK.level));
    b.day = numOr(ctx.day, FALLBACK.day);

    var npc = ctx.npc;
    if (typeof npc === 'string' && npc !== '') b.npc = npc;
    else if (npc && typeof npc === 'object') b.npc = firstOf(npc.name, npc.title, FALLBACK.npc);
    else b.npc = firstOf(ctx.npcName, FALLBACK.npc);

    b.target = firstOf(ctx.target, ctx.foe, FALLBACK.target);
    b.item = firstOf(ctx.item, ctx.itemName, FALLBACK.item);
    b.gold = firstOf(ctx.gold, FALLBACK.gold);
    b.roll = numOr(ctx.roll, FALLBACK.roll);
    b.dc = numOr(ctx.dc, FALLBACK.dc);
    b.__bag = 1;
    return b;
  }

  // 替换占位符；未知键与空值都走兜底，输出里不会留下 undefined 或花括号。
  function fill(tpl, ctx) {
    var b = (ctx && ctx.__bag) ? ctx : bag(ctx);
    var out = String(tpl === null || tpl === undefined ? '' : tpl);
    out = out.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, function (m, key) {
      var v = b[key];
      if (v === undefined || v === null || v === '') v = FALLBACK[key];
      return plain(v);
    });
    return out.replace(/[{}]/g, '');
  }

  // 由 ctx 推出的确定性下标：同一次调用永远落在同一条模板上。
  function idxOf(ctx, kind, len, salt) {
    len = numOr(len, 0);
    if (len < 1) return 0;
    ctx = ctx || {};
    var t = Number(ctx.turn);
    if (!isFinite(t)) t = 0;
    var r = Number(ctx.roll);
    if (!isFinite(r)) r = 0;
    var raw = Math.floor(t * 7 + r + String(kind === undefined ? '' : kind).length + numOr(salt, 0));
    var i = raw % len;
    if (i < 0) i += len;
    return i;
  }

  // 词串的稳定指纹，用来让同一轮里不同类别落到不同条目上。
  function toneOf(s) {
    s = String(s === undefined || s === null ? '' : s);
    var h = 7;
    for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 9973;
    return h;
  }

  function beatCount(text) {
    var m = String(text).match(/[。！？]/g);
    return m ? m.length : 1;
  }


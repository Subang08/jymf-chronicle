  function scene(kind, ctx) {
    var k = plain(kind) || 'idle';
    var bank = SCENES[k] || SCENES.idle;
    var b = bag(ctx);
    var parts = [fill(bank[idxOf(ctx, k, bank.length)], b)];
    var n = beatCount(parts[0]);

    if (n < 2 && REFLEX_KINDS[k]) {
      parts.push(fill(REFLEX[idxOf(ctx, k, REFLEX.length, toneOf(k) + 3)], b));
      n += 1;
    }
    if (n < 3 && SPEAK_KINDS[k] && Math.abs(numOr(ctx && ctx.turn, 0)) % 2 === 1) {
      parts.push(fill(VOICE[idxOf(ctx, k, VOICE.length, toneOf(k) + 11)], b));
    }
    return parts.join('');
  }

  function talk(npc, topic, ctx) {
    var name = '';
    var role = '';
    if (npc && typeof npc === 'object') {
      name = firstOf(npc.name, npc.title);
      role = firstOf(npc.role, npc.job, npc.title);
    } else {
      name = plain(npc);
      role = name;
    }
    if (name === '') name = FALLBACK.npc;

    var key = roleKey(role + ' ' + name);
    var tp = plain(topic) || 'greet';
    var bankFor = TALK[key] || TALK.generic || {};
    var list = bankFor[tp] || bankFor.greet || ['他看了你一眼。｜“说不上来。”'];

    var b = bag(ctx);
    b.npc = name;
    var line = String(list[idxOf(ctx, key + tp, list.length, toneOf(name) + toneOf(role))] || list[0] || '');
    var cut = line.indexOf('｜');
    var beat = cut >= 0 ? line.slice(0, cut) : '';
    var words = cut >= 0 ? line.slice(cut + 1) : line;
    return fill(beat, b) + fill(words, b);
  }

  function openingScript(id) {
    var key = plain(id) || 'north';
    var src = OPENINGS[key] || OPENINGS.north || [];
    return src.map(function (node) {
      var opts = (node.opts || []).map(function (o) {
        return { k: o.k, label: o.label, kind: o.kind };
      });
      var hasCustom = opts.some(function (o) { return o.k === 'e'; });
      if (!hasCustom) opts.push({ k: CUSTOM_OPT.k, label: CUSTOM_OPT.label, kind: CUSTOM_OPT.kind });
      return { title: node.title, text: node.text, opts: opts };
    });
  }

